import { openSync, readSync, closeSync } from 'node:fs';
import path from 'node:path';
import imageMetaTable from '@/lib/data/image-meta.json';

// Intrinsic size of an image under /public, read from the file header at
// render time (server components only — pages using this are static, so it
// runs once at build). The fallback for images not yet in
// lib/data/image-meta.json (see getImageMeta below). Lets layouts show a screenshot at its own proportions
// instead of cropping it into a fixed frame. Handles PNG, JPEG and WebP,
// which is everything under /public/work and /public/projects.

export interface ImageDims {
  width: number;
  height: number;
}

const cache = new Map<string, ImageDims | null>();
const HEAD = 64 * 1024; // JPEG SOF can sit behind EXIF; 64 KB covers our files

function readHead(file: string): Buffer | null {
  let fd: number | undefined;
  try {
    fd = openSync(file, 'r');
    const buf = Buffer.alloc(HEAD);
    const n = readSync(fd, buf, 0, HEAD, 0);
    return buf.subarray(0, n);
  } catch {
    return null;
  } finally {
    if (fd !== undefined) closeSync(fd);
  }
}

function parse(b: Buffer): ImageDims | null {
  // PNG: IHDR is always the first chunk
  if (b.length >= 24 && b.readUInt32BE(0) === 0x89504e47) {
    return { width: b.readUInt32BE(16), height: b.readUInt32BE(20) };
  }
  // WebP: RIFF....WEBP then a VP8 / VP8L / VP8X chunk
  if (b.length >= 30 && b.toString('ascii', 0, 4) === 'RIFF' && b.toString('ascii', 8, 12) === 'WEBP') {
    const chunk = b.toString('ascii', 12, 16);
    if (chunk === 'VP8 ') return { width: b.readUInt16LE(26) & 0x3fff, height: b.readUInt16LE(28) & 0x3fff };
    if (chunk === 'VP8L') {
      const bits = b.readUInt32LE(21);
      return { width: (bits & 0x3fff) + 1, height: ((bits >> 14) & 0x3fff) + 1 };
    }
    if (chunk === 'VP8X') return { width: b.readUIntLE(24, 3) + 1, height: b.readUIntLE(27, 3) + 1 };
    return null;
  }
  // JPEG: walk the markers to the first start-of-frame
  if (b.length >= 4 && b[0] === 0xff && b[1] === 0xd8) {
    let i = 2;
    while (i + 9 < b.length) {
      if (b[i] !== 0xff) return null;
      const marker = b[i + 1];
      const len = b.readUInt16BE(i + 2);
      const isSof = marker >= 0xc0 && marker <= 0xcf && marker !== 0xc4 && marker !== 0xc8 && marker !== 0xcc;
      if (isSof) return { width: b.readUInt16BE(i + 7), height: b.readUInt16BE(i + 5) };
      i += 2 + len;
    }
  }
  return null;
}

export function getImageDims(src: string | undefined): ImageDims | null {
  if (!src || !src.startsWith('/')) return null;
  if (cache.has(src)) return cache.get(src)!;
  const buf = readHead(path.join(process.cwd(), 'public', src));
  const dims = buf ? parse(buf) : null;
  cache.set(src, dims && dims.width > 0 && dims.height > 0 ? dims : null);
  return cache.get(src)!;
}

// What a layout needs to place a project image without cropping it:
//   ratio — width / height of what should be shown
//   kind  — 'device' for a transparent mockup (floats on the ground, no
//           frame), 'screen' for a flat screenshot (gets a rounded frame)
//   box   — for a device, the visible area inside the file's transparent
//           margin, as fractions of the file, so the empty margin can be
//           dropped without touching a single visible pixel
export interface ImageMeta {
  src: string;
  width: number;
  height: number;
  ratio: number;
  kind: 'device' | 'screen';
  box?: { x: number; y: number; w: number; h: number };
}

// generated by scripts/image-meta.mjs; box is [x, y, width, height] in px
type MetaRow = { w: number; h: number; kind: string; box?: number[] };
const TABLE: Record<string, MetaRow> = imageMetaTable;

export function getImageMeta(src: string | undefined): ImageMeta | null {
  if (!src) return null;
  const row = TABLE[src];
  if (row) {
    const [bx, by, bw, bh] = row.box ?? [0, 0, row.w, row.h];
    return {
      src,
      width: row.w,
      height: row.h,
      ratio: bw / bh,
      kind: row.kind === 'device' ? 'device' : 'screen',
      box: row.box ? { x: bx / row.w, y: by / row.h, w: bw / row.w, h: bh / row.h } : undefined
    };
  }
  const dims = getImageDims(src);
  if (!dims) return null;
  return { src, width: dims.width, height: dims.height, ratio: dims.width / dims.height, kind: 'screen' };
}
